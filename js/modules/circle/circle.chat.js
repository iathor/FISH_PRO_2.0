  const activeChatChannelId = chatState.activeChatChannelId || '';
  const selectedChatMsgId = chatState.selectedChatMsgId || '';
  const isChatAttachSheetOpen = Boolean(chatState.isChatAttachSheetOpen);
  const chatComposerDraftText = chatState.chatComposerDraftText || '';

  if (!isFullScreenChatOpen || !activeChatChannelId) return '';
  const { explicitlyDeletedLocalIds } = getRelaySyncRuntimeRefs();
  const allMsgs = Array.isArray(s.chatMessages) ? s.chatMessages : [];
