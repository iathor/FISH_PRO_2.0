function haversineKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLon / 2) ** 2;
  return Math.round(R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a)) * 10) / 10;
}

function findNearestCity(lat, lon) {
  let best = QUICK_CITIES[0];
  let bestDist = Infinity;
  for (const c of QUICK_CITIES) {
    const d = haversineKm(lat, lon, c.lat, c.lon);
    if (d < bestDist) {
      bestDist = d;
      best = c;
    }
  }
  return { ...best, distKm: bestDist };
}

function decodeKplocToken(rawParam = '') {
  const str = String(rawParam || '').trim();
  if (!str.startsWith('KPLOC_')) return null;
  const parts = str.split('_');
  if (parts.length < 3) return null;
  const parseCoord = (p) => {
    if (!p) return NaN;
    const neg = p.startsWith('M') || p.startsWith('-');
    const clean = p.replace(/^[M-]/, '');
    const num = parseFloat(clean);
    if (!Number.isFinite(num)) return NaN;
    const val = (!clean.includes('.') && num > 180) ? (num / 10000) : num;
    return neg ? -val : val;
  };
  const lat = parseCoord(parts[1]);
  const lon = parseCoord(parts[2]);
  const fishId = parts.slice(3).join('_') || '';
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  return { lat, lon, fishId };
}

/**
 * Онлайн-геокодер для ЛЮБОГО города, посёлка, деревни или реки РФ, если его нет в статическом списке
 */
async function geocodePlaceOnline(placeQuery) {
  const clean = String(placeQuery || '').trim();
  if (clean.length < 2) return null;
  try {
    const url = `https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(clean)}&count=5&language=ru&format=json`;
    const res = await fetch(url, { headers: { 'User-Agent': 'KlevProClubBot/2.0.165 (https://klevpro.ru)' } });
    if (res.ok) {
      const data = await res.json();
      const results = Array.isArray(data?.results) ? data.results : [];
      const hit = results.find(r => r.country_code === 'RU') || results[0];
      if (hit && Number.isFinite(hit.latitude) && Number.isFinite(hit.longitude)) {
        const near = findNearestCity(hit.latitude, hit.longitude);
        return {
          name: hit.name || clean,
          lat: hit.latitude,
          lon: hit.longitude,
          basin: near.basin,
          water: hit.admin1 ? `${hit.admin1} • ${near.water}` : near.water,
          topFish: near.topFish
        };
      }
    }
  } catch (e) {}

  try {
    const nomUrl = `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(clean + ' Россия')}&format=json&limit=1&accept-language=ru`;
    const res = await fetch(nomUrl, { headers: { 'User-Agent': 'KlevProClubBot/2.0.165 (https://klevpro.ru)' } });
    if (res.ok) {
      const arr = await res.json();
      if (Array.isArray(arr) && arr[0]) {
        const lat = parseFloat(arr[0].lat);
        const lon = parseFloat(arr[0].lon);
        if (Number.isFinite(lat) && Number.isFinite(lon)) {
          const near = findNearestCity(lat, lon);
          const shortTitle = String(arr[0].display_name || clean).split(',')[0].trim();
          return {
            name: shortTitle || clean,
            lat,
            lon,
            basin: near.basin,
            water: near.water,
            topFish: near.topFish
          };
        }
      }
    }
  } catch (e) {}
  return null;
}

/**
 * Умный разбор запроса «Город/река + Рыба» со склонениями и онлайн-геокодером
 */
async function resolveQueryCityAndFish(rawQuery) {
  const q = String(rawQuery || '')
    .replace(/^\/(klev|crew|circle|start)(@\S+)?\s*/i, '')
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е');

  let matchedFish = null;
  let matchedKeyword = '';
  for (const f of BOT_FISH_CATALOG) {
    const kw = f.keywords.find(k => q.includes(k));
    if (kw) {
      matchedFish = f;
      matchedKeyword = kw;
      break;
    }
  }

  let matchedCity = null;
  for (const c of QUICK_CITIES) {
    const cNorm = c.name.toLowerCase().replace(/ё/g, 'е');
    if (q.includes(cNorm)) {
      matchedCity = c;
      break;
    }
    if (Array.isArray(c.stems) && c.stems.some(st => q.includes(st))) {
      matchedCity = c;
      break;
    }
  }

  // Если город не найден в быстром списке, извлекаем название места без названия рыбы и ищем онлайн!
  if (!matchedCity && q.length >= 2) {
    let placeCandidate = q;
    if (matchedKeyword) {
      for (const f of BOT_FISH_CATALOG) {
        for (const kw of f.keywords) {
          placeCandidate = placeCandidate.replace(new RegExp(`[а-яa-z0-9_-]*${kw}[а-яa-z0-9_-]*`, 'gi'), ' ');
        }
      }
    }
    placeCandidate = placeCandidate
      .replace(/\b(в|во|на|под|около|рядом|у|клев|прогноз|рыбалка|рыба|ловля|клюет|город|г|река|р|озеро|оз|вдхр)\b/gi, ' ')
      .replace(/\s+/g, ' ')
      .trim();

    if (placeCandidate.length >= 2) {
      const onlineCity = await geocodePlaceOnline(placeCandidate);
      if (onlineCity) {
        matchedCity = onlineCity;
      }
    }
  }

  const city = matchedCity || QUICK_CITIES[0];
  if (!matchedFish) {
    const topName = (city.topFish[0] || 'Щука').toLowerCase().replace(/ё/g, 'е');
    matchedFish = BOT_FISH_CATALOG.find(f => f.keywords.some(kw => topName.includes(kw))) || BOT_FISH_CATALOG[0];
  }

  return { city, fish: matchedFish };
}

async function fetchLiveSpotWeather(lat, lon) {
  try {
    const url = `https://api.met.no/weatherapi/locationforecast/2.0/compact?lat=${lat.toFixed(4)}&lon=${lon.toFixed(4)}`;
    const res = await fetch(url, {
      headers: { 'User-Agent': 'KlevProClubBot/2.0.165 (https://klevpro.ru)' }
    });
    if (res.ok) {
      const data = await res.json();
      const first = data?.properties?.timeseries?.[0]?.data?.instant?.details;
      const elev = data?.geometry?.coordinates?.[2] || 60;
      if (first) {
        const tAir = Math.round((first.air_temperature ?? 5) * 10) / 10;
        const pMm = Math.round((first.air_pressure_at_sea_level || 1013) * 0.750062 - elev / 11.5);
        const wind = Math.round((first.wind_speed ?? 3) * 10) / 10;
        const waterTemp = Math.max(0.4, Math.min(24, Math.round((tAir * 0.52 + 2.4) * 10) / 10));
        const iceText = tAir <= -6 && waterTemp <= 0.8
          ? '❄️ Устойчивый ледостав'
          : (tAir <= 2.5 && tAir >= -3.5 ? '🌊❄️ Шуга и забереги (сплошного льда нет)' : '🌊 Открытая вода');
        return { tAir, waterTemp, press: pMm, wind, iceText };
      }
    }
  } catch (e) {}
  return {
    tAir: 4.0,
    waterTemp: 4.5,
    press: 756,
    wind: 3.4,
    iceText: '🌊 Открытая вода'
  };
}

function computeFishScoreForWeather(fishObj, w) {
  const wt = w.waterTemp ?? 4.5;
  const [minOpt, maxOpt] = fishObj.optT || [6, 16];
  let score = 58;
  if (wt >= minOpt && wt <= maxOpt) {
    score += 20;
  } else if (wt < minOpt) {
    score += Math.max(-22, Math.round(fishObj.coldBonus - (minOpt - wt) * 3.5));
  } else {
    score -= Math.round((wt - maxOpt) * 3);
  }
  const pDiff = Math.abs((w.press || 755) - 755);
  score += Math.round(6 - Math.min(12, pDiff * 0.7));
  if (w.wind >= 1.5 && w.wind <= 5.5) score += 5;
  else if (w.wind > 8.5) score -= 12;
  return Math.max(18, Math.min(96, score));
}

