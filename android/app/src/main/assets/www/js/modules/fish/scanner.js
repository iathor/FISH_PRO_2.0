    const lCtrl = new AbortController();
    const lTimer = setTimeout(() => lCtrl.abort(), 3200);
    const lRes = await fetch('https://generativelanguage.googleapis.com/v1beta/models?key=' + encodeURIComponent(cleanKey), {
      method: 'GET',
      signal: lCtrl.signal
    }).catch(() => null);
